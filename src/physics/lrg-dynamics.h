/**
 * LrgDynamicsContact:
 * @body_a: first body id
 * @body_b: second body id
 * @kind: which pair produced the contact
 * @point: world point (the deepest point, between the two surfaces)
 * @normal: unit world normal pointing from A to B (moving B along it
 *   separates the pair). Note that lrg_dynamics_world_get_contact()
 *   reports the opposite direction (the 0.8 "pushes A out" normal)
 * @depth: penetration of the deepest point, before the solve (negative
 *   for a speculative contact that is still apart)
 * @n_points: points in the manifold (1 .. 4)
 * @normal_impulse: total normal impulse (N·s) the last substep applied
 * @relative_speed: closing speed (m/s) along @normal when the contact
 *   was generated (positive while approaching)
 *
 * One contact manifold between two bodies. A plain boxed struct, filled
 * by lrg_dynamics_world_get_contact_info() and passed to
 * #LrgDynamicsWorld::contact-added.
 */
typedef struct {
    guint                  body_a;
    guint                  body_b;
    LrgDynamicsContactKind kind;
    gfloat                 point[3];
    gfloat                 normal[3];
    gfloat                 depth;
    guint                  n_points;
    gfloat                 normal_impulse;
    gfloat                 relative_speed;
} LrgDynamicsContact;

